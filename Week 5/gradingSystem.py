grade = float(input("What is your total grade?  "))

if grade >= 90:
    print("You have an A grade")
elif grade >= 80:
    print("You have a B grade")
elif grade >= 70:
    print("You have a C grade")
elif grade >= 60:
    print("You have a D grade")
else:
    print("You have an F grade. You really should get it up")